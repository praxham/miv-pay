// Regenerates src/og-assets.ts (font + wasm embedded as base64).
// Run: bun scripts/embed-og-assets.ts   (needs the 3 packages installed)
import { readFileSync, writeFileSync } from "node:fs";

const b64 = (p: string) => readFileSync(p).toString("base64");
const nm = "node_modules";

const out = `// AUTO-GENERATED by scripts/embed-og-assets.ts - do not edit.
export const poppinsBold = "${b64(`${nm}/@expo-google-fonts/poppins/700Bold/Poppins_700Bold.ttf`)}";
export const poppinsMedium = "${b64(`${nm}/@expo-google-fonts/poppins/500Medium/Poppins_500Medium.ttf`)}";
export const resvgWasm = "${b64(`${nm}/@resvg/resvg-wasm/index_bg.wasm`)}";
`;
writeFileSync("src/og-assets.ts", out);
console.log(
  "wrote src/og/assets.ts",
  (out.length / 1024 / 1024).toFixed(2),
  "MB",
);
